use gtkg_extract::v04::{AnalysisContext, ExtractedFile, extract};

fn parse(path: &str, text: &str) -> ExtractedFile {
    extract(path, text.as_bytes(), &AnalysisContext::default()).expect("supported static source")
}
fn replay_spans(file: &ExtractedFile, text: &str) {
    for call in &file.calls {
        assert_eq!(&text[call.span.byte_start..call.span.byte_end], call.expression);
        assert_eq!(text[..call.span.byte_start].bytes().filter(|x| *x == b'\n').count()+1, call.span.line_start);
    }
    for decl in &file.declarations {
        assert_eq!(&text[decl.name_span.byte_start..decl.name_span.byte_end], decl.name);
        assert!(decl.span.byte_start <= decl.name_span.byte_start && decl.span.byte_end >= decl.name_span.byte_end);
    }
}

#[test]
fn python_preserves_full_calls_repeated_sites_and_shadowing_scopes() {
    let text = "import os as operating\ndef f():\n    return 1\ndef outer():\n    f()\n    f()\n    def inner(exists):\n        exists = False\n        operating.path.exists('中')\n        str(exists)\n        return f()\n    return inner(True)\n";
    let f = parse("pkg/a.py", text);
    assert_eq!(f.parse_status,"parsed");
    assert_eq!(f.calls.len(),6);
    let calls: Vec<_> = f.calls.iter().filter(|c| c.expression=="f()").collect();
    assert_eq!(calls.len(),3);
    assert_ne!(calls[0].id,calls[1].id);
    assert_eq!(calls[0].scope_id,calls[1].scope_id);
    assert_ne!(calls[0].scope_id,calls[2].scope_id);
    let external = f.calls.iter().find(|c| c.expression=="operating.path.exists('中')").unwrap();
    assert_eq!(external.receiver.as_deref(),Some("operating.path"));
    assert_eq!(external.callee,"exists");
    assert!(f.declarations.iter().any(|d| d.name=="exists" && d.kind=="parameter" && d.callability=="unknown"));
    assert!(f.declarations.iter().any(|d| d.name=="exists" && d.kind=="variable" && d.callability=="non_callable"));
    assert_eq!((f.imports[0].module.as_str(),f.imports[0].alias.as_str()),("os","operating"));
    replay_spans(&f,text);
}

#[test]
fn go_records_core_declarations_receivers_aliases_and_entire_expressions() {
    let text = "package engine\nimport ext \"example.org/dependency\"\ntype Worker struct { Ready bool; Name string }\ntype Runner interface { Run() error }\nfunc helper[T any](v T) T { return v }\nfunc (w *Worker) Run(x int) error {\n ext.Send(w.Name)\n helper[int](x)\n w.Ready = true\n return nil\n}\n";
    let f=parse("engine/main.go",text);
    assert_eq!(f.package.as_deref(),Some("engine"));
    assert_eq!(f.parser_identity,"tree-sitter-go/0.23.4/abi14");
    assert_eq!(f.semantic_status,"analyzed");
    for name in ["Worker","Ready","Name","Runner","Run","helper","w","x","v"] { assert!(f.declarations.iter().any(|d|d.name==name),"missing {name}"); }
    let run=f.declarations.iter().find(|d|d.name=="Run" && d.receiver_type.is_some()).unwrap();
    assert_eq!(run.receiver_type.as_deref(),Some("Worker"));
    assert!(run.signature.contains("(w *Worker)"));
    assert!(f.imports.iter().any(|i|i.module=="example.org/dependency" && i.alias=="ext"));
    assert!(f.calls.iter().any(|c|c.expression=="helper[int](x)" && c.callee=="helper"));
    assert!(f.limitations.iter().any(|x|x=="generic_type_solving_not_supported"));
    assert!(f.limitations.iter().any(|x|x=="interface_dispatch_not_proven"));
    replay_spans(&f,text);
}

#[test]
fn go_variant_ledger_is_context_bound_and_never_silently_analyzed() {
    let src="//go:build darwin && arm64 && !special\n\npackage p\nfunc f() {}\n";
    let active=parse("p/host_darwin_arm64.go",src);
    assert_eq!(active.variant_status,"active");
    let other=parse("p/host_linux.go","package p\nfunc f() {}\n");
    assert_eq!(other.variant_status,"inactive"); assert_eq!(other.semantic_status,"not_requested");
    assert!(other.limitations.iter().any(|x|x.starts_with("variant_filename:")));
    let cgo=parse("p/native.go","package p\nimport \"C\"\nfunc f() {}\n");
    assert_eq!(cgo.variant_status,"inactive"); assert!(cgo.limitations.iter().any(|x|x=="cgo_disabled"));
    let mut ctx=AnalysisContext::default();ctx.build_tags=vec!["special".into()];
    let tagged=extract("p/host.go",src.as_bytes(),&ctx).unwrap();
    assert_eq!(tagged.variant_status,"inactive"); assert_ne!(tagged.context_digest,active.context_digest);
    let generated=parse("p/generated.go","// Code generated by fixture. DO NOT EDIT.\npackage p\nfunc f() {}\n");
    assert!(generated.limitations.iter().any(|x|x=="generated_source"));
}

#[test]
fn javascript_and_typescript_keep_methods_parameters_local_bindings_and_calls() {
    for (path,text) in [("a.js","import { send as transmit } from './net.js';\nfunction top(flag) { const exists = false; transmit(flag); obj.exists(); }\nclass A { f() { return top(true); } }\nclass B { f() { return top(false); } }"),("a.ts","import { send as transmit } from './net';\nfunction top(flag: boolean) { const exists: boolean = false; transmit(flag); obj.exists(); }\nclass A { f() { return top(true); } }\nclass B { f() { return top(false); } }")] {
        let f=parse(path,text); assert_eq!(f.calls.len(),4); assert_eq!(f.parse_status,"parsed");
        let methods:Vec<_>=f.declarations.iter().filter(|d|d.name=="f").collect();assert_eq!(methods.len(),2);assert_ne!(methods[0].scope_id,methods[1].scope_id);
        assert!(f.declarations.iter().any(|d|d.name=="flag" && d.kind=="parameter"));
        assert!(f.declarations.iter().any(|d|d.name=="exists" && d.callability=="non_callable"));
        assert!(f.imports.iter().any(|i|i.alias=="transmit" && i.symbol.as_deref()==Some("send")));
        assert!(f.calls.iter().any(|c|c.expression=="obj.exists()" && c.receiver.as_deref()==Some("obj")));
        replay_spans(&f,text);
    }
}

#[test]
fn rust_keeps_utf8_byte_spans_nested_scopes_and_receiver_calls() {
    let text="use crate::net::send as transmit;\nstruct Worker { ready: bool }\nfn helper() {}\nimpl Worker { fn run(&self, flag: bool) { let exists = false; helper(); helper(); self.step(flag); } fn step(&self, flag: bool) {} }\nfn outer() { fn inner() { helper(); } inner(); let 中文 = \"文\"; transmit(中文); }";
    let f=parse("src/a.rs",text); assert_eq!(f.parse_status,"parsed");assert_eq!(f.calls.len(),6);
    assert!(f.declarations.iter().any(|d|d.name=="run" && d.receiver_type.as_deref()==Some("Worker")));
    assert!(f.declarations.iter().any(|d|d.name=="flag" && d.kind=="parameter"));
    assert!(f.declarations.iter().any(|d|d.name=="exists" && d.callability=="non_callable"));
    assert!(f.imports.iter().any(|i|i.module=="crate::net" && i.alias=="transmit" && i.symbol.as_deref()==Some("send")));
    assert!(f.calls.iter().any(|c|c.expression=="self.step(flag)" && c.receiver.as_deref()==Some("self")));
    replay_spans(&f,text);
}

#[test]
fn errors_identity_and_pure_determinism_are_explicit() {
    for (path,src) in [("broken.go","package p\nfunc f( {"),("broken.py","def f(:"),("broken.ts","function f( {"),("broken.rs","fn f( {")] {
        let f=parse(path,src);assert_eq!(f.parse_status,"error");assert_ne!(f.semantic_status,"analyzed");assert!(f.limitations.iter().any(|x|x=="parse_error"));
    }
    let a=parse("a.py","def f():\n    f()\n");let b=parse("a.py","def f():\n    f()\n");assert_eq!(a,b);
    let changed=parse("a.py","def f():\n    f()\n# new\n");assert_ne!(a.calls[0].id,changed.calls[0].id);
    assert!(extract("a.py",&[0xff],&AnalysisContext::default()).is_err());
}
